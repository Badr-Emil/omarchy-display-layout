// Run with: node --test tests/
const test = require("node:test")
const assert = require("node:assert/strict")
const Layout = require("../Layout.js")

function rect(name, x, y, w, h) {
  return {
    name: name, description: name + " display", width: w, height: h,
    refreshRate: 60, scale: 1, transform: 0, x: x, y: y, w: w, h: h
  }
}

function valid(rects) {
  for (let i = 0; i < rects.length; i++) {
    let attached = rects.length === 1
    for (let j = 0; j < rects.length; j++) {
      if (i === j) continue
      assert.equal(Layout.overlaps(rects[i], rects[j]), false, rects[i].name + " overlaps " + rects[j].name)
      if (Layout.touches(rects[i], rects[j])) attached = true
    }
    assert.ok(attached, rects[i].name + " is detached")
  }
  assert.equal(Math.max(...Layout.islands(rects)), 0, "layout is split into islands")
  const box = Layout.bounds(rects)
  assert.deepEqual([box.x, box.y], [0, 0])
}

test("logical size follows scale and rotation", () => {
  assert.deepEqual(Layout.logicalSize(1920, 1080, 1.5, 0), { w: 1280, h: 720 })
  assert.deepEqual(Layout.logicalSize(1920, 1080, 1, 1), { w: 1080, h: 1920 })
  assert.deepEqual(Layout.logicalSize(2560, 1440, 0, 2), { w: 2560, h: 1440 })
})

test("parseMonitors drops disabled and mirrored outputs", () => {
  const raw = JSON.stringify([
    { name: "eDP-2", description: "AU Optronics", width: 1920, height: 1080, refreshRate: 240, x: 10, y: 20, scale: 1.5, transform: 0, mirrorOf: "none", disabled: false },
    { name: "DP-1", width: 1920, height: 1080, scale: 1, mirrorOf: "eDP-2", disabled: false },
    { name: "DP-2", width: 1920, height: 1080, scale: 1, mirrorOf: "none", disabled: true }
  ])
  const monitors = Layout.parseMonitors(raw)
  assert.equal(monitors.length, 1)
  assert.deepEqual([monitors[0].w, monitors[0].h, monitors[0].x, monitors[0].y], [1280, 720, 10, 20])
  assert.deepEqual(Layout.parseMonitors("not json"), [])
})

test("snap pulls a dragged display onto a neighbour's edge", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 3000, 500, 1280, 720)]
  assert.deepEqual(Layout.snap(rects, 1, 1950, 25, 60), { x: 1920, y: 0 })
  assert.deepEqual(Layout.snap(rects, 1, 2400, 700, 60), { x: 2400, y: 700 })
})

test("a display dropped on top of another is pushed to the nearest side", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 5000, 0, 1280, 720)]
  const moved = Layout.move(rects, 1, 1500, 100)
  valid(moved)
  assert.deepEqual([moved[1].x, moved[1].y], [1920, 100])
})

test("a display dropped far away is pulled back against the layout", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 1920, 0, 1280, 720)]
  const moved = Layout.move(rects, 1, 9000, 4000)
  valid(moved)
  assert.equal(moved[1].x, 1920)
  assert.equal(moved[1].y, 1080 - Layout.MIN_SHARED)
})

test("moving left of the origin renormalizes to 0x0", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 1920, 0, 1280, 720)]
  const moved = Layout.move(rects, 1, -1280, 0)
  valid(moved)
  assert.deepEqual([moved[1].x, moved[0].x], [0, 1280])
})

test("a valid drop position is kept as is", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 1920, 0, 1280, 720)]
  const moved = Layout.move(rects, 1, 1920, 360)
  assert.deepEqual([moved[1].x, moved[1].y], [1920, 360])
})

test("settle never lands on a third display", () => {
  const rects = [
    rect("A", 0, 0, 1920, 1080),
    rect("B", 1920, 0, 1920, 1080),
    rect("C", 3840, 0, 1920, 1080),
    rect("D", 0, 1080, 1280, 720)
  ]
  for (let x = -2500; x <= 6500; x += 450) {
    for (let y = -1500; y <= 2500; y += 350) {
      valid(Layout.move(rects, 3, x, y))
    }
  }
})

test("place puts a display on each side of the others", () => {
  const rects = [rect("A", 0, 0, 1920, 1080), rect("B", 1920, 0, 1280, 720)]
  const left = Layout.place(rects, 1, "left", "center")
  valid(left)
  assert.deepEqual([left[1].x, left[1].y, left[0].x], [0, 180, 1280])

  const top = Layout.place(rects, 1, "top", "start")
  valid(top)
  assert.deepEqual([top[1].x, top[1].y, top[0].y], [0, 0, 720])

  const bottom = Layout.place(rects, 1, "bottom", "end")
  valid(bottom)
  assert.deepEqual([bottom[1].x, bottom[1].y], [640, 1080])
})

test("row lines displays up in their current order", () => {
  const rects = [
    rect("A", 2983, 1263, 1280, 720),
    rect("B", 1063, 903, 1920, 1080),
    rect("C", 4263, 0, 2560, 1440)
  ]
  const lined = Layout.row(rects, "bottom")
  valid(lined)
  assert.deepEqual(lined.map(r => [r.x, r.y]), [[1920, 720], [0, 360], [3200, 0]])
})

const config = [
  "-- Generated by nwg-displays",
  "",
  "hl.env(\"GDK_SCALE\", \"2\")",
  "hl.monitor({ output = \"\", mode = \"preferred\", position = \"auto\", scale = \"auto\" })",
  "-- hl.monitor({ output = \"HDMI-A-1\", mode = \"preferred\", position = \"9x9\", scale = 1 })",
  "hl.monitor({",
  "    output = \"eDP-2\",",
  "    mode = \"1920x1080@240.0\",",
  "    position = \"2983x1263\",",
  "    scale = 1.5,",
  "    vrr = 0",
  "})",
  "hl.monitor({ output = \"desc:Lenovo Group Limited C27q-35\", scale = 1 })",
  ""
].join("\n")

test("updateConfig only replaces positions of existing rules", () => {
  const edp = rect("eDP-2", 0, 360, 1920, 1080)
  const out = Layout.updateConfig(config, [edp])
  assert.equal(out, config.replace("2983x1263", "0x360"))
})

test("updateConfig matches desc: rules and inserts a missing position", () => {
  const dock = rect("DP-3", 1280, 0, 2560, 1440)
  dock.description = "Lenovo Group Limited C27q-35 URHK8KND"
  const out = Layout.updateConfig(config, [dock])
  assert.ok(out.includes("hl.monitor({ output = \"desc:Lenovo Group Limited C27q-35\", position = \"1280x0\", scale = 1 })"))
  assert.ok(!out.includes("Added by Display Layout"))
})

test("updateConfig appends rules for displays without one and skips comments", () => {
  const hdmi = rect("HDMI-A-1", 1280, 0, 1920, 1080)
  hdmi.description = "Lenovo Group Limited LEN L24e-20 0x34464C4D"
  const edp = rect("eDP-2", 0, 360, 1920, 1080)
  edp.description = "AU Optronics 0x048E"
  const out = Layout.updateConfig(config, [edp, hdmi])
  assert.ok(out.includes("position = \"9x9\""), "commented rule must stay untouched")
  assert.ok(out.includes("position = \"auto\""), "wildcard rule must stay untouched")
  assert.ok(out.endsWith(
    "\n-- Added by Display Layout\n" +
    "hl.monitor({ output = \"desc:Lenovo Group Limited LEN L24e-20 0x34464C4D\", mode = \"1920x1080@60\", position = \"1280x0\", scale = 1 })\n"
  ))
  assert.ok(Layout.isSaved(out, [edp, hdmi]))
  assert.equal(Layout.updateConfig(out, [edp, hdmi]), out)
})

test("updateConfig works on an empty file", () => {
  const edp = rect("eDP-2", 0, 0, 1920, 1080)
  assert.equal(
    Layout.updateConfig("", [edp]),
    "-- Added by Display Layout\nhl.monitor({ output = \"eDP-2\", mode = \"1920x1080@60\", position = \"0x0\", scale = 1 })\n"
  )
})

test("outputKey falls back to the connector for identical displays", () => {
  const a = rect("DP-3", 0, 0, 1920, 1080)
  const b = rect("DP-4", 1920, 0, 1920, 1080)
  a.description = b.description = "Twin Display"
  assert.equal(Layout.outputKey(a, [a, b]), "DP-3")
  b.description = "Other Display"
  assert.equal(Layout.outputKey(a, [a, b]), "desc:Twin Display")
})

test("isSaved compares against the stored positions", () => {
  const edp = rect("eDP-2", 2983, 1263, 1920, 1080)
  assert.equal(Layout.isSaved(config, [edp]), true)
  edp.x = 0
  assert.equal(Layout.isSaved(config, [edp]), false)
  assert.equal(Layout.isSaved(config, [rect("HDMI-A-1", 9, 9, 1920, 1080)]), false)
  assert.equal(Layout.isSaved("", []), false)
})

test("liveScript replays the user's rule and falls back to a plain one", () => {
  const edp = rect("eDP-2", 0, 360, 1920, 1080)
  edp.scale = 1.5
  edp.refreshRate = 240
  const dock = rect("DP-5", 1280, 0, 2560, 1080)
  dock.refreshRate = 89.909
  dock.transform = 1
  assert.equal(Layout.liveScript(config, [edp, dock]), [
    "hl.monitor({ output = \"eDP-2\", mode = \"1920x1080@240.0\", position = \"0x360\", scale = 1.5, vrr = 0 })",
    "hl.monitor({ output = \"DP-5\", mode = \"2560x1080@89.909\", position = \"1280x0\", scale = 1, transform = 1 })"
  ].join("\n"))
})

test("rules that use Lua variables are not replayed", () => {
  assert.equal(Layout.isSelfContained("hl.monitor({ output = \"a = b\", scale = 1.5, vrr = true })"), true)
  assert.equal(Layout.isSelfContained("hl.monitor({ output = \"eDP-1\", scale = my_scale })"), false)
  const text = "local my_scale = 2\nhl.monitor({ output = \"eDP-1\", position = \"5x5\", scale = my_scale })\n"
  const edp = rect("eDP-1", 0, 0, 1920, 1080)
  assert.equal(
    Layout.liveScript(text, [edp]),
    "hl.monitor({ output = \"eDP-1\", mode = \"1920x1080@60\", position = \"0x0\", scale = 1 })"
  )
})

test("moving the display that links two groups pulls the groups together", () => {
  // The real five-display desk: 1 and 2 only reach the others through 3.
  const rects = [
    rect("eDP-2", 2983, 1263, 1280, 720),
    rect("HDMI-A-1", 1063, 903, 1920, 1080),
    rect("DP-3", 4263, 0, 2560, 1440),
    rect("DP-4", 6823, 0, 1920, 1080),
    rect("DP-5", 8743, 0, 2560, 1080)
  ]
  valid(Layout.normalize(rects))
  const moved = Layout.place(rects, 2, "top", "center")
  valid(moved)
  // The pair moved as one piece: 1 still sits right of 2, 360 lower.
  assert.deepEqual([moved[0].x - moved[1].x, moved[0].y - moved[1].y], [1920, 360])

  for (let x = -3000; x <= 12000; x += 700) {
    for (let y = -2500; y <= 3500; y += 500) {
      for (let i = 0; i < rects.length; i++) valid(Layout.move(rects, i, x, y))
    }
  }
})

test("liveScript leaves displays alone that did not move", () => {
  const a = rect("DP-1", 0, 0, 1920, 1080)
  const b = rect("DP-2", 1920, 0, 1920, 1080)
  const moved = Layout.move([a, b], 1, 1920, 500)
  assert.equal(
    Layout.liveScript("", moved, [a, b]),
    "hl.monitor({ output = \"DP-2\", mode = \"1920x1080@60\", position = \"1920x500\", scale = 1 })"
  )
  assert.equal(Layout.liveScript("", [a, b], [a, b]), "")
})
